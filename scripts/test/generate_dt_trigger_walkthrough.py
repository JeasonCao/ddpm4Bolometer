def _extract_func(src: str, func_name: str) -> str:
    """Pull a top-level function's full source text (def ... through the
    line before the next top-level def/class or EOF) out of a module's
    source text, by simple indentation scanning — no AST needed."""
    lines = src.splitlines()
    start = None
    for i, line in enumerate(lines):
        if re.match(rf'^def {re.escape(func_name)}\s*\(', line):
            start = i
            break
    if start is None:
        raise ValueError(f'Function {func_name} not found')
    end = len(lines)
    for j in range(start + 1, len(lines)):
        if re.match(r'^(def |class )', lines[j]):
            end = j
            break
    return '\n'.join(lines[start:end]).rstrip()


def _extract_const(src: str, name: str) -> str:
    m = re.search(rf'^{re.escape(name)}\s*=\s*(.+)$', src, re.MULTILINE)
    return m.group(1).split('#')[0].strip() if m else '?'


def _b64_img(path: str) -> str:
    with open(path, 'rb') as f:
        return base64.b64encode(f.read()).decode('ascii')


def _code_block(code: str, label: str = '') -> str:
    esc = html.escape(code)
    cap = f'<div class="code-label">{html.escape(label)}</div>' if label else ''
    return f'{cap}<pre class="code"><code>{esc}</code></pre>'


